# Create a working 16-bit bootloader image with proper boot signature

# Boot code in hex - simple bootloader that displays "B-Free OS Boot OK"
$bootCode = @(
    # Jump and header (62 bytes padding)
    0xEB, 0x3C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  # Jump over header
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    
    # Real boot code starts at 0x7c00
    # Set up segments
    0xB8, 0x00, 0x00,                      # mov ax, 0x0000
    0x8E, 0xD8,                            # mov ds, ax
    0x8E, 0xC0,                            # mov es, ax
    0x8E, 0xD0,                            # mov ss, ax
    
    # Set stack
    0xBC, 0x00, 0x7C,                      # mov sp, 0x7c00

    # Set video mode to 80x25 text (BIOS mode 3) to ensure text output behaves
    0xB4, 0x00, 0xB0, 0x03, 0xCD, 0x10,    # mov ah,0x00; mov al,0x03; int 0x10

    # Clear screen using int 0x10 AH=0x06 (scroll/clear)
    0xB4, 0x06,                            # mov ah, 0x06 (scroll/clear)
    0xB0, 0x00,                            # mov al, 0x00 (clear entire screen)
    0xB7, 0x0F,                            # mov bh, 0x0F (white on black)
    0xB9, 0x00, 0x00,                      # mov cx, 0x0000
    0xBA, 0x4F, 0x18,                      # mov dx, 0x184F
    0xCD, 0x10,                            # int 0x10
    
    # Reset cursor to top-left
    0xB4, 0x02,                            # mov ah, 0x02 (set cursor)
    0xB7, 0x00,                            # mov bh, 0x00
    # Move cursor to roughly center of 80x25 text (row=12, col=31)
    # DX = (row << 8) | col = 0x0C1F -> little-endian bytes 0x1F, 0x0C
    0xBA, 0x1F, 0x0C,                      # mov dx, 0x0C1F (row=12,col=31)
    0xCD, 0x10,                            # int 0x10
    
    # Now print message using teletype output (int 0x10 AH=0x0E)
    # Message: "B-Free OS Boot OK" (17 chars)
    
    # 'B'
    0xB4, 0x0E,                            # mov ah, 0x0E (teletype)
    0xB0, 0x42,                            # mov al, 'B'
    0xB7, 0x00,                            # mov bh, 0x00
    0xCD, 0x10,                            # int 0x10
    
    # '-'
    0xB4, 0x0E, 0xB0, 0x2D, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'F'
    0xB4, 0x0E, 0xB0, 0x46, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'r'
    0xB4, 0x0E, 0xB0, 0x72, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'e'
    0xB4, 0x0E, 0xB0, 0x65, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'e'
    0xB4, 0x0E, 0xB0, 0x65, 0xB7, 0x00, 0xCD, 0x10,
    
    # ' '
    0xB4, 0x0E, 0xB0, 0x20, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'O'
    0xB4, 0x0E, 0xB0, 0x4F, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'S'
    0xB4, 0x0E, 0xB0, 0x53, 0xB7, 0x00, 0xCD, 0x10,
    
    # ' '
    0xB4, 0x0E, 0xB0, 0x20, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'B'
    0xB4, 0x0E, 0xB0, 0x42, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'o'
    0xB4, 0x0E, 0xB0, 0x6F, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'o'
    0xB4, 0x0E, 0xB0, 0x6F, 0xB7, 0x00, 0xCD, 0x10,
    
    # 't'
    0xB4, 0x0E, 0xB0, 0x74, 0xB7, 0x00, 0xCD, 0x10,
    
    # ' '
    0xB4, 0x0E, 0xB0, 0x20, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'O'
    0xB4, 0x0E, 0xB0, 0x4F, 0xB7, 0x00, 0xCD, 0x10,
    
    # 'K'
    0xB4, 0x0E, 0xB0, 0x4B, 0xB7, 0x00, 0xCD, 0x10,
    
    
    0xB4, 0x02,                            # mov ah, 0x02 (INT13 read)
    0xB0, 0xFF,                            # mov al, <SECTORS> (placeholder, patched later)
    0xB5, 0x00,                            # mov ch, 0x00 (cylinder)
    0xB1, 0x02,                            # mov cl, 0x02 (start sector = 2)
    0xB6, 0x00,                            # mov dh, 0x00 (head)
    0xBB, 0x00, 0x80,                      # mov bx, 0x8000 (buffer offset)
    0xCD, 0x13,                            # int 0x13 (read sectors)
    0xEA, 0x00, 0x80, 0x00, 0x00,          # jmp 0x0000:0x8000 (far jump to loaded kernel)
    # If read fails, loop
    0xEB, 0xFE                             # jmp $
) | ForEach-Object { [byte]$_ }

# Pad to 510 bytes
while ($bootCode.Count -lt 510) {
    $bootCode += [byte]0x00
}

# Add boot signature (0xAA55 in little-endian)
$bootCode += [byte]0x55
$bootCode += [byte]0xAA

# Read kernel (2ndboot64) and append to image
$kernelPath = "c:\Users\h_kis\Desktop\B-Free-master\Program\btron-pc\boot\2nd\2ndboot64"
if (-Not (Test-Path $kernelPath)) {
    Write-Error "Kernel not found: $kernelPath. Build it first with 'make 2ndboot64'"
    exit 1
}
$kernelBytes = [System.IO.File]::ReadAllBytes($kernelPath)
$sectorCount = [int][math]::Ceiling($kernelBytes.Length / 512.0)

# Patch placeholder sector count (first occurrence of 0xFF in loader area)
$patched = $false
for ($i = 0; $i -lt $bootCode.Count; $i++) {
    if ($bootCode[$i] -eq 0xFF) {
        $bootCode[$i] = [byte]($sectorCount -band 0xFF)
        $patched = $true
        break
    }
}
if (-not $patched) {
    Write-Error "Failed to patch sector count placeholder"
    exit 1
}

# Combine boot sector and kernel, pad kernel to full sectors
$totalKernelSize = $sectorCount * 512
if ($kernelBytes.Length -lt $totalKernelSize) {
    $pad = New-Object byte ($totalKernelSize - $kernelBytes.Length)
    for ($i=0; $i -lt $pad.Length; $i++) { $pad[$i] = 0 }
    $kernelBytes = $kernelBytes + $pad
}

$outPath = "c:\Users\h_kis\Desktop\B-Free-master\Program\btron-pc\boot\2nd\bootdisk.img"
[System.IO.File]::WriteAllBytes($outPath, $bootCode + $kernelBytes)

Write-Host "Boot disk image created: $(Split-Path -Leaf $outPath)"
Write-Host "Size: $($bootCode.Count + $kernelBytes.Length) bytes (boot + $sectorCount sectors)"
Write-Host ""
Write-Host "To run with QEMU:"
Write-Host "  qemu-system-x86_64 -m 512 -fda bootdisk.img"
